/**
 * Whether this player plays runtime content: an error when the version of
 * pixi-animate-runtime that generated it is outside the range the player
 * plays, a warning when it is newer than the player (it may hold what the
 * player does not know and leaves out).
 */
function checkRuntimeContent(data: IRuntimeData): void {
	const made = typeof data.runtimeVersion === 'string' ? data.runtimeVersion : '';
	const check = checkVersion(made, RUNTIME_CONTENT_RANGE, VERSION);
	const by = 'This runtime content was generated by pixi-animate-runtime ' + (made || '(no version)');
	if (check.error) {
		throw new Error(by + ', which this player (' + VERSION + ') does not play (it plays runtime content generated by ' + RUNTIME_CONTENT_RANGE + '). '
			+ (check.newer ? 'Update the player.' : 'Generate the runtime content again with pixi-animate-runtime ' + VERSION + '.'));
	}
	if (check.warning) {
		console.warn(by + ', newer than this player (' + VERSION + '). What the newer version added may not play; update the player.');
	}
}

export type TMovieClipClass = new (mode?: string | null, startPosition?: number | null, loop?: boolean | number | null) => MovieClip;
export type TSpriteClass = new () => Sprite;
export type TBitmapClass = new () => Bitmap;
export type TSymbolClass = TMovieClipClass | TSpriteClass | TBitmapClass;

/**
 * The symbol classes of a content by symbol id: what published code calls `lib`.
 */
export interface ILibrary {
	[id: string]: TSymbolClass;
}

/**
 * The createjs-compatible names frame scripts reach as `cjs` / `createjs`.
 */
export const namespace = {
	DisplayObject, Container, MovieClip, Shape, Graphics, Sprite, SpriteSheet, Bitmap, Text,
	ColorFilter, ButtonHelper, Event, EventDispatcher, Rectangle, Point: PIXI.Point
};

export type TNamespace = typeof namespace;

/** What frame scripts get for the template's global playSound: nothing is played */
export interface ISilentSound {
	paused: boolean;
	volume: number;
	addEventListener(): void;
	removeEventListener(): void;
	on(): void;
	stop(): void;
	play(): void;
}

function playSound(): ISilentSound {
	return {
		paused: false, volume: 1,
		addEventListener() { /* silent */ }, removeEventListener() { /* silent */ },
		on() { /* silent */ }, stop() { /* silent */ }, play() { /* silent */ }
	};
}

export interface IGeneratedContent {
	data: IRuntimeData;
	scripts: TScript[];
	writers: TWriter[];
	memberWriters: TMemberWriter[];
}

/**
 * What runtime content exports: given the names frame scripts refer
 * to, it returns the content's data and its frame scripts (as code, closed
 * over those names). exportRoot and stage are passed as undefined: they are
 * the template's root and stage, which a player of any symbol does not have.
 */
export type TContentFactory = (cjs: TNamespace, createjs: TNamespace, lib: ILibrary, exportRoot: undefined, stage: undefined, playSound: () => ISilentSound) => IGeneratedContent;

export interface IContentAssets {
	/** Textures of the manifest images (sprite sheet atlases included), by manifest id */
	images?: { [id: string]: PIXI.Texture };
}

function isMovieClipClass(content: Content, id: string, value: TSymbolClass): value is TMovieClipClass {
	const def = content.data.symbols[id];
	return !!def && def.kind === 'movieclip';
}

function isSpriteClass(content: Content, id: string, value: TSymbolClass): value is TSpriteClass {
	const def = content.data.symbols[id];
	return !!def && def.kind === 'sprite';
}

function isBitmapClass(content: Content, id: string, value: TSymbolClass): value is TBitmapClass {
	const def = content.data.symbols[id];
	return !!def && def.kind === 'bitmap';
}

function toRect(rect: IRectDef | null): Rectangle | null {
	return rect ? new Rectangle(rect.x, rect.y, rect.width, rect.height) : null;
}

function toRects(rects: IRectDef[] | null): Rectangle[] | null {
	return rects ? rects.map(rect => new Rectangle(rect.x, rect.y, rect.width, rect.height)) : null;
}

function numbers(value: TDataValue): number[] {
	return Array.isArray(value) ? value.map(v => (typeof v === 'number' ? v : 0)) : [0, 0, 0, 0];
}

/**
 * The template's AdobeAn.handleFilterCache: re-caches the instances a clip's
 * filterCacheList names while the clip is within their frame ranges.
 */
function handleFilterCache(event: Event): void {
	if (event.paused) {
		return;
	}
	const target = event.target;
	if (!(target instanceof MovieClip) || !target.filterCacheList) {
		return;
	}
	target.filterCacheList.forEach(entry => {
		if (entry.startFrame <= target.currentFrame && target.currentFrame <= entry.endFrame) {
			entry.instance.cache(entry.x, entry.y, entry.w, entry.h);
		}
	});
}

/** A value of the published lib.properties (width, height, fps, color, ...) */
export type TContentProperty = number | string | boolean | null;

export interface IContentProperties {
	[key: string]: TContentProperty;
}

/**
 * A loaded content, as the application uses it.
 */
export interface IContent {
	/** The composition id (lib.properties.id of the published content) */
	readonly id: string;
	/** The symbol classes by symbol name: what frame scripts reach as `lib` */
	readonly lib: ILibrary;
	/** The values of the published lib.properties (its lists, such as the manifest, left out) */
	readonly properties: Readonly<IContentProperties>;
	/**
	 * An instance of a symbol for the application to place, set up as the HTML
	 * template sets up the root it creates.
	 */
	create(id: string): DisplayObject;
}

/** A MovieClip symbol as the player builds its instances from: its slots with every field */
interface IMovieClipPlan extends Omit<IRuntimeMovieClipDef, 'slots' | 'tweens'> {
	slots: IRuntimeSlotDef[];
	tweens: IRuntimeTweenDef[];
}

/**
 * A content: the symbol classes built from generated data, sharing one
 * definition per symbol. Not part of the API: applications get an IContent.
 * @internal
 */
export class Content implements ITextureSource {
	readonly data: IRuntimeData;
	readonly scripts: TScript[];
	readonly writers: TWriter[];
	readonly memberWriters: TMemberWriter[];
	readonly lib: ILibrary = {};
	readonly images: { [id: string]: IImageAsset } = {};
	/** One Graphics per drawing of the content, shared by every symbol that shows it */
	readonly graphics: Graphics[] = [];
	readonly spriteSheets: { [name: string]: SpriteSheet } = {};
	private readonly _frameAssets: { [key: string]: IImageAsset } = {};

	constructor(factory: TContentFactory, assets?: IContentAssets) {
		const generated = factory(namespace, namespace, this.lib, undefined, undefined, playSound);
		checkRuntimeContent(generated.data);
		this.data = generated.data;
		this.scripts = generated.scripts;
		this.writers = generated.writers;
		this.memberWriters = generated.memberWriters;

		this.data.graphics.forEach(def => {
			this.graphics.push(new Graphics(commandsOf(this.data.commandKinds, def), this));
		});

		this._applyImages(assets && assets.images ? assets.images : {});

		Object.keys(this.data.symbols).forEach(id => {
			const def = this.data.symbols[id];
			if (def.kind === 'movieclip') {
				this.lib[id] = this._movieClipClass(def);
			} else if (def.kind === 'sprite') {
				this.lib[id] = this._spriteClass(def);
			} else if (def.kind === 'bitmap') {
				this.lib[id] = this._bitmapClass(def);
			}
		});
	}

	/**
	 * Sets the textures of the content's images (by manifest id) and the sprite
	 * sheets cut from them. Done before any instance is made: the constructor's
	 * assets, or the textures a loader read for the content afterwards.
	 */
	_applyImages(textures: { [id: string]: PIXI.Texture }): void {
		this.data.images.forEach(entry => {
			const texture = textures[entry.id];
			this.images[entry.id] = { src: entry.src, texture: texture || PIXI.Texture.EMPTY };
		});
		this.data.spriteSheets.forEach(sheet => {
			const image = this.images[sheet.name] || { src: sheet.name, texture: PIXI.Texture.EMPTY };
			this.spriteSheets[sheet.name] = new SpriteSheet(image, sheet.frames.map(numbers));
		});
	}

	image(id: string): PIXI.Texture | null {
		const image = this.images[id];
		return image ? image.texture : null;
	}

	frame(sheet: string, index: number): PIXI.Texture | null {
		const spriteSheet = this.spriteSheets[sheet];
		return spriteSheet ? spriteSheet.textures[index] || null : null;
	}

	imageAsset(id: string): IImageAsset | null {
		return this.images[id] || null;
	}

	/** The image a frame of a sheet is drawn into for a bitmap fill (named after the atlas and the frame) */
	frameAsset(sheet: string, index: number): IImageAsset | null {
		const key = sheet + '#' + index;
		let asset = this._frameAssets[key];
		if (!asset) {
			const spriteSheet = this.spriteSheets[sheet];
			const texture = spriteSheet ? spriteSheet.textures[index] : undefined;
			if (!spriteSheet || !texture) {
				return null;
			}
			asset = this._frameAssets[key] = { src: spriteSheet.frames[index].image.src + '#' + index, texture };
		}
		return asset;
	}

	/**
	 * An instance of a symbol for the application to place, set up as the HTML
	 * template sets up the root it creates: a clip that re-caches its children's
	 * color effects (it has a filterCacheList) gets the filter cache handling,
	 * which published code otherwise gets from the symbol that creates it (an
	 * instance made by `new lib[id]()` in a frame script gets none, as in
	 * CreateJS). The handling does not change what the player draws (it draws
	 * color effects without caches); it keeps the instance's state the
	 * template's.
	 */
	create(id: string): DisplayObject {
		const symbolClass = this.lib[id];
		if (!symbolClass) {
			throw new Error('no symbol "' + id + '"');
		}
		const instance = new symbolClass();
		if (instance instanceof MovieClip && instance.filterCacheList) {
			instance.addEventListener('tick', handleFilterCache);
		}
		return instance;
	}

	private _movieClipClass(data: IRuntimeMovieClipDef): TMovieClipClass {
		const content = this;
		// The slots filled in, and the display lists turned back into entries, once for the symbol, not for every instance
		const templates = this.data.slotTemplates;
		const def: IMovieClipPlan = Object.assign({}, data, { slots: data.slots.map(ref => slotOf(templates, ref)), tweens: data.tweens.map(tweenOf) });
		// The symbol's drawings, from the content's table (shared with every symbol that shows the same drawing)
		const graphics = def.graphics.map(index => content.graphics[index]);
		const fps = typeof this.data.properties.fps === 'number' ? this.data.properties.fps : null;
		const nominalBounds = toRect(def.nominalBounds);
		const frameBounds = toRects(def.frameBounds);

		return class extends MovieClip {
			constructor(mode?: string | null, startPosition?: number | null, loop?: boolean | number | null) {
				// Constructed with no arguments (a root, or new lib.X()): the resolved defaults
				const defaults = def.defaults;
				const noArgs = mode === undefined && startPosition === undefined && loop === undefined;
				super(
					noArgs && defaults ? defaults.mode : mode,
					noArgs && defaults ? defaults.startPosition : startPosition,
					noArgs && defaults ? defaults.loop : loop,
					new Timeline(def.duration, def.labels)
				);
				this.contentFps = fps;
				if (nominalBounds) {
					this.nominalBounds = nominalBounds;
				}
				if (frameBounds) {
					this.frameBounds = frameBounds;
				}
				content._populate(this, def, graphics);
			}
		};
	}

	private _spriteClass(def: ISpriteSymbolDef): TSpriteClass {
		const content = this;
		const nominalBounds = toRect(def.nominalBounds);
		const frameBounds = toRects(def.frameBounds);
		return class extends Sprite {
			constructor() {
				super(content._sheet(def.sprite.sheet));
				if (nominalBounds) {
					this.nominalBounds = nominalBounds;
				}
				if (frameBounds) {
					this.frameBounds = frameBounds;
				}
				content._applySprite(this, def.sprite);
			}
		};
	}

	private _bitmapClass(def: IBitmapSymbolDef): TBitmapClass {
		const content = this;
		const nominalBounds = toRect(def.nominalBounds);
		const frameBounds = toRects(def.frameBounds);
		return class extends Bitmap {
			constructor() {
				super(content._image(def.bitmap.image));
				if (nominalBounds) {
					this.nominalBounds = nominalBounds;
				}
				if (frameBounds) {
					this.frameBounds = frameBounds;
				}
				content._applyBitmap(this, def.bitmap);
			}
		};
	}

	private _sheet(name: string): SpriteSheet {
		const sheet = this.spriteSheets[name];
		if (!sheet) {
			throw new Error('no sprite sheet "' + name + '"');
		}
		return sheet;
	}

	private _image(id: string): IImageAsset | null {
		return this.images[id] || null;
	}

	_applySprite(sprite: Sprite, def: ISpriteDef | null): void {
		if (!def) {
			return;
		}
		sprite.spriteSheet = this._sheet(def.sheet);
		if (def.paused) {
			sprite.gotoAndStop(def.frame);
		} else {
			sprite.gotoAndPlay(def.frame);
		}
	}

	_applyBitmap(bitmap: Bitmap, def: IBitmapDef | null): void {
		if (!def) {
			return;
		}
		bitmap.image = this._image(def.image);
		bitmap.sourceRect = toRect(def.sourceRect);
	}

	private _createSlot(slot: IRuntimeSlotDef, graphics: Graphics[]): DisplayObject {
		const symbol = slot.symbol;
		const symbolClass = symbol ? this.lib[symbol] : undefined;

		if (slot.kind === 'movieclip') {
			if (!symbol || !symbolClass || !isMovieClipClass(this, symbol, symbolClass)) {
				throw new Error('missing MovieClip symbol ' + symbol);
			}
			return new symbolClass(slot.mode, slot.startPosition, slot.loop);
		}

		if (slot.kind === 'shape') {
			return new Shape(slot.graphics === null ? null : graphics[slot.graphics]);
		}

		if (slot.kind === 'sprite') {
			let sprite: Sprite;
			if (symbol && symbolClass && isSpriteClass(this, symbol, symbolClass)) {
				sprite = new symbolClass();
			} else {
				sprite = new Sprite(this._sheet(slot.sprite ? slot.sprite.sheet : ''));
			}
			this._applySprite(sprite, slot.sprite);
			return sprite;
		}

		if (slot.kind === 'bitmap') {
			let bitmap: Bitmap;
			if (symbol && symbolClass && isBitmapClass(this, symbol, symbolClass)) {
				bitmap = new symbolClass();
			} else {
				bitmap = new Bitmap(null);
			}
			this._applyBitmap(bitmap, slot.bitmap);
			return bitmap;
		}

		if (slot.kind === 'text') {
			const props = slot.text || {};
			const text = new Text(String(props.text == null ? '' : props.text), typeof props.font === 'string' ? props.font : undefined, typeof props.color === 'string' ? props.color : undefined);
			Object.keys(props).forEach(key => {
				Reflect.set(text, key, props[key]);
			});
			return text;
		}

		throw new Error('unsupported display object in the content data');
	}

	/**
	 * Builds an instance of a MovieClip symbol: what the published
	 * constructor builds, from the shared definition.
	 */
	_populate(self: MovieClip, def: IMovieClipPlan, graphics: Graphics[]): void {
		const slots = def.slots.map(slot => {
			const obj = this._createSlot(slot, graphics);
			if (slot.initWriter !== null) {
				this.writers[slot.initWriter](obj, slot.initValues === null ? undefined : slot.initValues);
			}
			if (slot.parentSet) {
				obj.parent = self;
			}
			if (slot.filters) {
				obj.filters = slot.filters.map(filter => {
					const p = filter.props;
					const n = (key: string): number => { const v = p[key]; return typeof v === 'number' ? v : 0; };
					return new ColorFilter(n('redMultiplier'), n('greenMultiplier'), n('blueMultiplier'), n('alphaMultiplier'),
						n('redOffset'), n('greenOffset'), n('blueOffset'), n('alphaOffset'));
				});
			}
			if (slot.cache) {
				const c = slot.cache;
				obj.cache(c.x, c.y, c.width, c.height, c.scale);
			}
			return obj;
		});

		const resolve = (target: TTargetDef): object => {
			if (target.type === 'self') {
				return self;
			}
			if (target.type === 'slot') {
				return slots[target.slot];
			}
			if (target.type === 'filter') {
				const filters = slots[target.slot].filters;
				return filters ? filters[target.filter] : {};
			}
			return {};
		};

		def.slots.forEach((slot, i) => {
			const obj = slots[i];
			if (slot.mask !== null) {
				obj.mask = slots[slot.mask];
			}
			if (slot.button) {
				const b = slot.button;
				const hit = b.hit === null ? null : slots[b.hit];
				if (obj instanceof MovieClip) {
					new ButtonHelper(obj, b.out, b.over, b.down, b.play, hit instanceof MovieClip ? hit : null, b.hitFrame);
				}
				if (hit && !(hit instanceof MovieClip)) {
					obj.hitArea = hit;
				}
			} else if (slot.hitArea !== null) {
				obj.hitArea = slots[slot.hitArea];
			}
			if (slot.filterCacheListener) {
				obj.addEventListener('tick', handleFilterCache);
			}
		});

		if (def.filterCacheList) {
			self.filterCacheList = def.filterCacheList.map(entry => {
				const instance = resolve(entry.instance);
				return {
					instance: instance instanceof DisplayObject ? instance : self,
					startFrame: entry.startFrame, endFrame: entry.endFrame,
					x: entry.x, y: entry.y, w: entry.w, h: entry.h
				};
			});
		}

		if (def.memberWriter !== null) {
			this.memberWriters[def.memberWriter](self, slots);
		}
		def.unmanaged.forEach(index => {
			self.addChild(slots[index]);
		});

		const content = this;
		const scope: ITweenScope = {
			stateTarget(entry: IStateEntryDef): DisplayObject | null {
				const target = resolve(entry.target);
				return target instanceof DisplayObject ? target : null;
			},
			value(value: TFrameValue): TWrittenValue {
				if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
					return graphics[value.graphics] || null;
				}
				return value;
			},
			script(index: number): TScript {
				return content.scripts[index];
			},
			writer(index: number): TWriter {
				return content.writers[index];
			}
		};

		def.tweens.forEach(tween => {
			self.timeline.tweens.push(new TweenState(tween, resolve(tween.target), scope, self));
		});

		self._renderFirstFrame();
	}
}

/**
 * What the application gets of a content: the content itself stays out of
 * reach, the methods closing over it.
 */
export function contentInterface(content: Content): IContent {
	const properties: IContentProperties = {};
	Object.keys(content.data.properties).forEach(key => {
		const value = content.data.properties[key];
		if (value === null || typeof value === 'number' || typeof value === 'string' || typeof value === 'boolean') {
			properties[key] = value;
		}
	});
	const id = properties.id;
	return {
		id: typeof id === 'string' ? id : '',
		lib: content.lib,
		properties: Object.freeze(properties),
		create(symbol: string): DisplayObject {
			return content.create(symbol);
		}
	};
}

/**
 * Plays one frame of a display tree the way createjs does on a stage update:
 * the tick phase (playheads advance, children in reverse order, tick
 * listeners), then the resolve phase (each MovieClip settles its timeline,
 * children in reverse order).
 */
export function tick(root: DisplayObject, event?: Event): void {
	root._tick(event || new Event('tick'));
	resolveState(root);
}

/**
 * The resolve phase alone: each MovieClip settles its timeline (children in
 * reverse order), without playing a frame.
 */
export function resolveState(node: DisplayObject): void {
	if (node instanceof MovieClip) {
		node._updateState();
	}
	if (node instanceof Container) {
		const children = node.children;
		for (let i = children.length - 1; i >= 0; i--) {
			if (children[i] instanceof MovieClip) {
				resolveState(children[i]);
			}
		}
	}
}
